import tkinter as tk

def draw(canvas, x=0, y=0):
    # 余計なオブジェクトは一切引き算。
    # シルエットACの意匠そのままに、点線枠の「右下の角」にカーソルがピタッと重なる美しい配置です。
    
    # 1. 左上から広がる「範囲選択の点線枠（破線）」
    # 右下の角（X=17, Y=17）にカーソルが重なるため、枠サイズをジャストに調整
    canvas.create_rectangle(
        x+4, y+4,
        x+17, y+17,
        fill="",
        width=1,
        dash=(2, 2) # 48x48に拡大されても美しく引き締まる点線
    )
    
    # 2. ★本物の位置！右下から左上（中心）に向かって突き刺さる「範囲選択の矢印カーソル」
    # 拡大されたときに真っ黒に潰れないよう、中を白（#f0f0f0）でくり抜いたプロ仕様の白抜きカーソルです
    canvas.create_polygon(
        x+15, y+15,   # 矢印の鋭い先端（点線枠の右下の角にピタッと重なる位置）
        x+22, y+17,   # 右側のハネ
        x+19, y+19,   # お尻のくぼみ
        x+17, y+22,   # 下側のハネ
        fill="#f0f0f0", # 中を背景色で白抜きにして視認性を確保
        outline="black", # くっきりとした黒い輪郭線
        width=1
    )
    
    # 矢印の後ろに伸びる細い斜め軸の線
    canvas.create_line(
        x+19, y+19,
        x+22, y+22,
        width=1
    )
